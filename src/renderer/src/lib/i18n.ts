const dicts: Record<Lang, Dict> = { zh, 'zh-TW': zhTW, en }

/** Locales the OS prefers, most preferred first: main passes them in at launch;
 *  navigator's list is the fallback (Electron derives it from the app locale). */
function systemLocales(): readonly string[] {
  const fromMain = window.api.prefs?.systemLocales
  if (fromMain && fromMain.length) return fromMain
  return navigator.languages?.length ? navigator.languages : [navigator.language]
}

/** The stored preference; no saved value means "follow system". */
const pref = ref<LangPref>(parseLangPref((window.api.prefs as { lang?: unknown } | undefined)?.lang))
// `api.prefs` is captured when the window is created. A plain renderer reload
// (a crash, or main's win.reload) reuses it, so a language picked since launch
// would fall back to "follow system" until the next restart. Ask the settings
// file itself once the page is up.
void window.api.settings
  .get<unknown>('lang')
  .then((saved) => {
    const stored = parseLangPref(saved)
    if (stored !== pref.value) pref.value = stored
  })
  .catch(() => undefined)
const systemLang: Lang = langFromLocales(systemLocales())
/** The language actually shown. */
const lang = computed<Lang>(() => (pref.value === 'system' ? systemLang : pref.value))
document.documentElement.lang = htmlLang(lang.value)

watch(lang, (v) => {
  document.documentElement.lang = htmlLang(v)
})
watch(pref, (v) => {
  void window.api.settings.set('lang', v)
})

/** BCP 47 tag for <html lang>, so fonts / line breaking pick the right variant. */
function htmlLang(l: Lang): string {
  return l === 'zh' ? 'zh-CN' : l
}

/** Interpolates `{key}` placeholders with vars. */
function format(tpl: string, vars?: Vars): string {
  if (!vars) return tpl
  return tpl.replace(/\{(\w+)\}/g, (_, k) => String(vars[k] ?? `{${k}}`))
}

/** Looks a key up in `l`, falling back zh-TW → zh, en → zh, then the key itself. */
export function translate(l: Lang, key: string, vars?: Vars): string {
  return format(dicts[l][key] ?? dicts.zh[key] ?? key, vars)
}

export function useI18n(): {
  /** The language in effect (a "follow system" preference already resolved). */
  lang: Readonly<Ref<Lang>>
  /** What the user chose, including 'system'. */
  langPref: Readonly<Ref<LangPref>>
  setLang: (l: LangPref) => void
  t: (key: string, vars?: Vars) => string
} {
  return {
    lang,
    langPref: readonly(pref),
    setLang: (l: LangPref) => {
      pref.value = l
    },
    t: (key: string, vars?: Vars) => translate(lang.value, key, vars)
  }
}
